import crypto from 'crypto';
import fs from 'fs';
import path from 'path';

/**
 * Cache freshness and generation coordination for media. Pure with respect to
 * import time (no directories created, no environment read): thumbnailUtils.ts
 * wires it to the real cache directories and tests use it on temp fixtures.
 */

// ---- HTTP cache policy -------------------------------------------------------

/**
 * Generated media URLs are not content-hashed, so a response may only be reused
 * after revalidation (ETag / Last-Modified -> 304), and never by shared caches
 * (the content may be authorization-dependent).
 */
export const MEDIA_CACHE_CONTROL = 'private, no-cache';

/** Strong validator for generated bytes (content hash: identical bytes -> identical tag). */
export function contentEtag(data: Uint8Array): string {
    return `"${crypto.createHash('sha1').update(data).digest('hex')}"`;
}

/** Weak validator for files served straight from the library (size + mtime). */
export function fileEtag(size: number, mtimeMs: number): string {
    return `W/"${size.toString(16)}-${Math.floor(mtimeMs).toString(16)}"`;
}

export interface Validators {
    etag: string;
    /** Epoch milliseconds, when cheaply known. */
    lastModifiedMs?: number | null;
}

export function validatorHeaders(v: Validators): Record<string, string> {
    const headers: Record<string, string> = { 'Cache-Control': MEDIA_CACHE_CONTROL, 'ETag': v.etag };
    if (v.lastModifiedMs != null && Number.isFinite(v.lastModifiedMs)) {
        headers['Last-Modified'] = new Date(v.lastModifiedMs).toUTCString();
    }
    return headers;
}

const stripWeak = (tag: string) => tag.trim().replace(/^W\//, '');

/** RFC 9110 conditional GET: If-None-Match wins; If-Modified-Since is consulted only without it. */
export function isNotModified(request: Request, v: Validators): boolean {
    if (request.method !== 'GET' && request.method !== 'HEAD') return false;

    const inm = request.headers.get('if-none-match');
    if (inm !== null) {
        if (inm.trim() === '*') return true;
        const ours = stripWeak(v.etag);
        return inm.split(',').some(t => stripWeak(t) === ours);
    }

    const ims = request.headers.get('if-modified-since');
    if (ims && v.lastModifiedMs != null) {
        const since = Date.parse(ims);
        if (Number.isFinite(since)) return Math.floor(v.lastModifiedMs / 1000) <= Math.floor(since / 1000);
    }
    return false;
}

export function notModifiedResponse(v: Validators): Response {
    return new Response(null, { status: 304, headers: validatorHeaders(v) });
}

// ---- Thumbnail settings -------------------------------------------------------

export const THUMBNAIL_DEFAULTS = { height: 400, quality: 80 } as const;
export const THUMBNAIL_HEIGHT_RANGE = { min: 16, max: 2000 } as const;
export const THUMBNAIL_QUALITY_RANGE = { min: 1, max: 100 } as const;

export interface ThumbnailSettings {
    height: number;
    quality: number;
}

function boundedInteger(
    name: string, raw: string | undefined, fallback: number, range: { min: number; max: number }, warn: (message: string) => void
): number {
    if (raw === undefined || raw.trim() === '') return fallback;
    const text = raw.trim();
    const value = /^\d+$/.test(text) ? Number(text) : NaN;
    if (!Number.isSafeInteger(value) || value < range.min || value > range.max) {
        warn(`Invalid ${name}=${JSON.stringify(raw.slice(0, 40))}: expected an integer from ${range.min} to ${range.max}; using ${fallback}.`);
        return fallback;
    }
    return value;
}

/** Validates once; never returns NaN or an out-of-range value. Invalid input warns and falls back to the default. */
export function resolveThumbnailSettings(
    env: Record<string, string | undefined>, warn: (message: string) => void
): ThumbnailSettings {
    const safeWarn = (message: string) => { try { warn(message); } catch { /* reporting is best-effort */ } };
    return {
        height: boundedInteger('THUMBNAIL_HEIGHT', env.THUMBNAIL_HEIGHT, THUMBNAIL_DEFAULTS.height, THUMBNAIL_HEIGHT_RANGE, safeWarn),
        quality: boundedInteger('THUMBNAIL_QUALITY', env.THUMBNAIL_QUALITY, THUMBNAIL_DEFAULTS.quality, THUMBNAIL_QUALITY_RANGE, safeWarn)
    };
}

// ---- Generation / invalidation coordination -----------------------------------

export type MediaKind = 'thumbnail' | 'preview';
const KINDS: MediaKind[] = ['thumbnail', 'preview'];

interface Job {
    promise: Promise<Buffer | null>;
    /** Set by invalidate(): the result may still be returned to its callers but must not be cached. */
    stale: boolean;
}

/**
 * Coalesces cache-miss generation per (kind, item), bounds aggregate concurrency,
 * and keeps invalidated jobs from repopulating the cache.
 *
 * Coordination design: each in-flight job carries a `stale` flag. invalidate(id)
 * flags the item's in-flight jobs and callers never join a stale job (a new one
 * starts, replacing it in the map). A job re-checks the flag after its temp file
 * is fully written and publishes it with a SYNCHRONOUS rename, so the check and
 * the publish cannot interleave with a synchronous invalidation (which also
 * unlinks the cache files): either the invalidation came first and the temp file
 * is discarded, or the publish came first and the invalidation's unlink removes
 * it. State is only held while a job runs (no per-item history to grow).
 */
export class MediaGenerationCoordinator {
    private readonly jobs = new Map<string, Job>();
    private active = 0;
    private readonly waiters: Array<() => void> = [];

    constructor(
        private readonly maxConcurrent = 4,
        private readonly log: { error: (...args: any[]) => void } = { error: (...a) => { try { console.error(...a); } catch { } } }
    ) { }

    private key(kind: MediaKind, id: string) {
        return `${kind}:${id}`;
    }

    /** Marks in-flight work for `id` stale. Synchronous; call it before/while deleting the cache files. */
    invalidate(id: string): void {
        for (const kind of KINDS) {
            const job = this.jobs.get(this.key(kind, id));
            if (job) job.stale = true;
        }
    }

    get inFlight(): number {
        return this.jobs.size;
    }

    generate(kind: MediaKind, id: string, cacheFile: string, produce: () => Promise<Buffer | null>): Promise<Buffer | null> {
        const key = this.key(kind, id);
        const existing = this.jobs.get(key);
        if (existing && !existing.stale) return existing.promise;

        const job: Job = { stale: false, promise: undefined as unknown as Promise<Buffer | null> };
        job.promise = this.run(job, cacheFile, produce).finally(() => {
            if (this.jobs.get(key) === job) this.jobs.delete(key);
        });
        this.jobs.set(key, job);
        return job.promise;
    }

    private async run(job: Job, cacheFile: string, produce: () => Promise<Buffer | null>): Promise<Buffer | null> {
        const buffer = await this.limited(produce);
        if (!buffer) return null;
        await this.commit(job, cacheFile, buffer);
        return buffer;
    }

    /** Atomic publish: temp file in the same directory, then rename; never a partially written cache file. */
    private async commit(job: Job, cacheFile: string, buffer: Buffer): Promise<void> {
        if (job.stale) return;
        const temp = `${cacheFile}.${process.pid}.${Math.random().toString(36).slice(2)}.tmp`;
        try {
            await fs.promises.writeFile(temp, buffer);
            if (job.stale) {
                fs.rmSync(temp, { force: true });
                return;
            }
            fs.renameSync(temp, cacheFile);
        } catch (error) {
            try { fs.rmSync(temp, { force: true }); } catch { }
            this.log.error(`Failed to write cache file ${path.basename(cacheFile)}:`, error);
        }
    }

    /** Counting semaphore with slot hand-off (a woken waiter inherits the releaser's slot). */
    private async limited<T>(fn: () => Promise<T>): Promise<T> {
        if (this.active >= this.maxConcurrent) {
            await new Promise<void>(resolve => this.waiters.push(resolve));
        } else {
            this.active++;
        }
        try {
            return await fn();
        } finally {
            const next = this.waiters.shift();
            if (next) next();
            else this.active--;
        }
    }
}
